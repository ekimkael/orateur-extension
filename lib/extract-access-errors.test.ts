import assert from "node:assert/strict"
import test from "node:test"
import { JSDOM } from "jsdom"
import { extractArticle, visibleText } from "./extract-article.ts"

const prose = "When a request fails, readers should receive an explanation instead of hearing the server error as an article. Publishers can investigate the problem and restore access to their original reporting without changing the requested page. "

test("CloudFront error pages are rejected by extraction and the text fallback", () => {
  // Observed on Scientific American: a 403 page long enough for visibleText.
  const doc = new JSDOM(`<html><head><title>ERROR: The request could not be satisfied</title></head><body>
    <h1>403 ERROR</h1><h2>The request could not be satisfied.</h2>
    ${prose.repeat(3)}<br>Review the CloudFront documentation for help.
    <pre>Generated by cloudfront (CloudFront)\nRequest ID: example</pre>
  </body></html>`, { url: "https://www.scientificamerican.com/article/example/" }).window.document
  const before = doc.documentElement.outerHTML

  assert.throws(() => extractArticle(doc), /article lisible/)
  assert.equal(visibleText(doc).text, "")
  assert.equal(doc.documentElement.outerHTML, before)
})

test("editorial coverage of CloudFront errors remains readable", () => {
  const doc = new JSDOM(`<html lang="en"><head><title>How publishers investigate delivery failures</title></head><body>
    <article><h1>How publishers investigate delivery failures</h1>
    <p>${prose}</p><p>${prose}</p>
    <pre>Generated by cloudfront (CloudFront)\nRequest ID: example</pre>
    <p>${prose}</p></article>
  </body></html>`, { url: "https://news.example.com/server-errors" }).window.document

  assert.ok(extractArticle(doc).textContent.includes(prose.trim()))
  assert.ok(visibleText(doc).text.includes(prose.trim()))
})

test("Bloomberg's full-page robot check is not read by the text fallback", () => {
  const doc = new JSDOM(`<html lang="en"><head><title>Bloomberg - Are you a robot?</title></head><body>
    <h1>We've detected unusual activity from your computer network</h1>
    <div id="px-captcha"></div><div class="info">${prose.repeat(3)}</div>
  </body></html>`, { url: "https://www.bloomberg.com/news/articles/example" }).window.document
  const before = doc.documentElement.outerHTML

  assert.throws(() => extractArticle(doc), /article lisible/)
  assert.equal(visibleText(doc).text, "")
  assert.equal(doc.documentElement.outerHTML, before)
})
