import assert from "node:assert/strict"
import test from "node:test"
import { JSDOM } from "jsdom"
import { extractArticle } from "./extract-article.ts"

const lead = "Cette enquête présente les événements et explique leurs conséquences. Elle s'appuie sur plusieurs témoignages, des observations indépendantes et des données vérifiables pour permettre au lecteur de comprendre ce qui s'est passé."
const middle = "Les équipes ont recueilli des informations dans plusieurs régions. Elles ont comparé les résultats, interrogé les personnes concernées et examiné les décisions des autorités afin de distinguer les faits établis des questions encore ouvertes."
const ending = "Les prochaines semaines permettront de mesurer les effets de ces décisions. Les observateurs poursuivront leur travail, publieront leurs conclusions et expliqueront comment la situation évolue pour les habitants concernés par ces changements."

function documentFor(body: string, url: string) {
  return new JSDOM(`<html lang="fr"><head><title>Comprendre les événements et leurs conséquences</title></head><body>${body}</body></html>`, { url }).window.document
}

test("Al Jazeera retire les recommandations et alertes insérées entre deux paragraphes", () => {
  const doc = documentFor(`<main id="main-content-area">
    <header class="article-header"><p class="article__subhead">${lead}</p></header>
    <div class="wysiwyg wysiwyg--all-content">
      <p>${middle}</p>
      <section class="more-on"><h2 class="more-on__heading">Recommended Stories</h2><ul><li><a href="/other">list 1 of 3 Une autre histoire à découvrir</a></li></ul></section>
      <h2>Les conséquences locales</h2>
      <div class="nudge" data-testid="nudge"><span class="nudge__text">Get instant alerts and updates based on your interests. Be the first to know when big stories happen.</span><button>Yes, keep me updated</button></div>
      <p>${ending}</p>
    </div>
  </main>`, "https://www.aljazeera.com/news/2026/10/18/example")

  const { textContent } = extractArticle(doc)

  for (const paragraph of [lead, middle, ending]) assert.ok(textContent.includes(paragraph))
  assert.match(textContent, /Les conséquences locales/)
  assert.doesNotMatch(textContent, /Recommended Stories|list 1 of 3|autre histoire|instant alerts|big stories happen/)
  assert.ok(doc.querySelector(".more-on"))
})

test("DW conserve le chapeau extérieur au corps sans lire vidéo ni promotion Google", () => {
  const doc = documentFor(`<article><div class="content-area">
    <header><p class="teaser-text">${lead}</p></header>
    <div class="rich-text">
      <p>${middle}</p>
      <h2>Pourquoi les habitants s'interrogent</h2>
      <p>${ending}</p>
      <div class="vjs-wrapper embed big"><h2>Watch our related video</h2><div class="render-container"><div class="vjs-duration-text">10:39</div></div></div>
      <p><em>If you rely on our team for trusted reporting, please select our <a href="https://www.google.com/preferences/source?q=dw.com">Preferred Source on Google</a>.</em></p>
    </div>
  </div></article>`, "https://www.dw.com/en/example/a-79692322")

  const { textContent } = extractArticle(doc)

  for (const paragraph of [lead, middle, ending]) assert.ok(textContent.includes(paragraph))
  assert.ok(textContent.indexOf(lead) < textContent.indexOf(middle))
  assert.match(textContent, /Pourquoi les habitants s'interrogent/)
  assert.doesNotMatch(textContent, /related video|10:39|Preferred Source|trusted reporting/)
  assert.ok(doc.querySelector("header > .teaser-text"))
})

