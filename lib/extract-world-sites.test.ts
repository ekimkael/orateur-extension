test("ABC ne répète pas les dates présentes dans les variantes écran, accessibilité et impression", () => {
  const doc = documentFor(`<article>
    <span class="ArticleHeadlineTitle_metaTimestamp__Ri6e7">Posted
      <time data-component="Timestamp" aria-hidden="true">9 Oct 2026 at 2:05am</time><time data-component="ScreenReaderTimestamp">9 Oct 2026 at 2:05am</time><time data-component="PrintTimestamp">9 Oct 2026 at 2:05am</time>, updated
      <time data-component="Timestamp" aria-hidden="true">9 Oct 2026 at 9:53am</time><time data-component="ScreenReaderTimestamp">9 Oct 2026 at 9:53am</time><time data-component="PrintTimestamp">9 Oct 2026 at 9:53am</time>
    </span>
    <p>${lead}</p><h2>Comprendre les observations</h2><p>${middle}</p><p>${ending}</p>
  </article>`, "https://www.abc.net.au/news/science/2026-10-09/example/107233640")

  const { textContent } = extractArticle(doc)

  assert.equal(textContent.match(/9 Oct 2026 at 2:05am/g)?.length, 1)
  assert.equal(textContent.match(/9 Oct 2026 at 9:53am/g)?.length, 1)
  assert.match(textContent, /Posted.*9 Oct 2026 at 2:05am, updated.*9 Oct 2026 at 9:53am/)
  for (const paragraph of [lead, middle, ending]) assert.ok(textContent.includes(paragraph))
  assert.equal(doc.querySelectorAll("[data-component='PrintTimestamp']").length, 2)
})
